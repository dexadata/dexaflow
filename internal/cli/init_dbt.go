package cli

import "fmt"

// dbtScaffoldFiles returns the files `dexaflow init --dbt` writes, keyed by
// slash-separated path. The shape is the hybrid one the docs teach (ADR 0043),
// and each part of it closes a gap that let #17 and #20 ship:
//
//   - Python tasks around the group, not Bash ones. runner.py re-imports dag.py
//     for every python task, which is the path where `from dexaflow import
//     dbt_group` has to resolve inside the task (#17).
//   - No Dockerfile, so the generated one, which installs `dependencies:`, is
//     the one that runs (#20).
//   - dbt-core and dbt-duckdb pinned together in `dependencies:`. Pinning only
//     the adapter lets pip resolve a dbt-core the adapter was not released with.
//   - A duckdb project with no profiles.yml and no `connection:`, so Lite writes
//     its zero-config duckdb profile and the first run needs no warehouse.
//
// examples/dbt_hybrid is this output under its own dag id, checked by
// TestDbtExampleMatchesTheInitScaffold.
func dbtScaffoldFiles(dagID string) map[string]string {
	return map[string]string{
		projectConfigFile:                        fmt.Sprintf(dbtProjectConfigTemplate, dagID),
		"dag.py":                                 fmt.Sprintf(dbtDagTemplate, dagID, dagID),
		".gitignore":                             dbtGitignoreTemplate,
		"transform/dbt_project.yml":              dbtProjectYAML,
		"transform/seeds/orders.csv":             dbtOrdersSeed,
		"transform/models/stg_orders.sql":        dbtStgOrdersModel,
		"transform/models/revenue_by_region.sql": dbtRevenueModel,
	}
}

const dbtProjectConfigTemplate = `schema_version: "1.0"
dag_id: %s
description: Python tasks around an embedded dbt project (duckdb).
python_version: "3.11"
# dbt itself is a dependency of the DAG image. dbt-core is pinned next to the
# adapter so pip cannot pick a dbt-core the adapter was not released with.
dependencies:
  - "dbt-core==1.9.*"
  - "dbt-duckdb==1.9.*"
# Each key is the name dag.py passes to dbt_group(). With no connection and no
# profiles.yml in the project, dexaflow lite writes a local duckdb profile.
dbt_groups:
  transform:
    project: transform
`

const dbtDagTemplate = `"""%s: Python tasks around an embedded dbt project."""
from __future__ import annotations

from airflow.sdk import DAG, task
from dexaflow import dbt_group


@task
def extract() -> int:
    # Stands in for the step that lands raw data; the dbt seed carries the rows.
    print("extract: orders are seeded by the dbt project")
    return 6


@task
def report(expected: int) -> None:
    print(f"report: dbt built the models over {expected} orders")


with DAG("%s", schedule=None, catchup=False, tags=["example", "dbt"]):
    rows = extract()
    models = dbt_group("transform")
    rows >> models >> report(rows)
`

const dbtGitignoreTemplate = `# Compiled artifact, regenerated by ` + "`dexaflow compile`" + `.
dag.json
# dbt build output and the local duckdb warehouse.
transform/target/
transform/logs/
*.duckdb
`

const dbtProjectYAML = `name: transform
version: "1.0.0"
profile: transform
model-paths: ["models"]
seed-paths: ["seeds"]
models:
  transform:
    +materialized: table
`

const dbtOrdersSeed = `order_id,region,amount
1,north,120
2,south,80
3,north,45
4,east,200
5,south,60
6,west,95
`

const dbtStgOrdersModel = `select order_id, region, amount
from {{ ref('orders') }}
`

const dbtRevenueModel = `select region, count(*) as orders, sum(amount) as revenue
from {{ ref('stg_orders') }}
group by region
`
