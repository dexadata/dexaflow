// workspaceGitignore is what `workspace init` ignores: compiled artifacts and
// Python caches, which change on every compile and conflict on every merge.
var workspaceGitignore = []string{"dag.json", "__pycache__/", ".venv/"}

// newWorkspaceCommand builds `dexaflow workspace`, the folder that holds many
// DAG projects and the targets they deploy to.
func newWorkspaceCommand() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "workspace",
		Short: "Create and manage a workspace (many DAGs, shared targets and defaults).",
		Long: "A workspace is a folder, usually a git repository, holding DAG projects under\n" +
			"dags/ and a dexaflow.workspace.yaml with the targets they deploy to and shared\n" +
			"defaults (registry, platforms, base image). Commands run anywhere inside it find\n" +
			"it by walking up to that file.",
	}
	cmd.AddCommand(newWorkspaceInitCommand())
	return cmd
}

func newWorkspaceInitCommand() *cobra.Command {
	var gitInit, force bool
	cmd := &cobra.Command{
		Use:   "init [dir]",
		Short: "Create a workspace: dexaflow.workspace.yaml, dags/ and .gitignore.",
		Args:  cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			dir := "."
			if len(args) == 1 {
				dir = args[0]
			}
			return runWorkspaceInit(cmd, dir, gitInit, force)
		},
	}
	cmd.Flags().BoolVar(&gitInit, "git", false, "also run `git init` when the folder is not in a git repository yet")
	cmd.Flags().BoolVar(&force, "force", false, "replace an existing workspace file")
	return cmd
}

func runWorkspaceInit(cmd *cobra.Command, dir string, gitInit, force bool) error {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return fmt.Errorf("resolving %s: %w", dir, err)
	}
	if existing := workspaceFileIn(abs); existing != "" && !force {
		return fmt.Errorf("%s is already a workspace (%s); pass --force to replace the file", abs, existing)
	}
	// A workspace inside another one hides the outer file from every command
	// run below it; that is rarely meant, so it takes --force.
	if outer, oerr := findWorkspace(filepath.Dir(abs)); oerr == nil && outer != nil && !force {
		return fmt.Errorf("%s is inside the workspace at %s (%s); commands run in the new one would no longer see the outer file. Add DAGs to the outer workspace with `dexaflow new`, or pass --force", abs, outer.Root, outer.File)
	}
	if err := os.MkdirAll(filepath.Join(abs, "dags"), 0o750); err != nil {
		return fmt.Errorf("creating %s: %w", filepath.Join(abs, "dags"), err)
	}
	files := map[string]string{
		workspaceFileName:                 workspaceFileTemplate,
		filepath.Join("dags", ".gitkeep"): "",
	}
	for name, content := range files {
		if werr := os.WriteFile(filepath.Join(abs, name), []byte(content), 0o644); werr != nil { //nolint:gosec // G306: shared, committed files with no secrets.
			return fmt.Errorf("writing %s: %w", name, werr)
		}
	}
	if gerr := ensureGitignore(filepath.Join(abs, ".gitignore"), workspaceGitignore); gerr != nil {
		return gerr
	}
	gitNote, gerr := maybeGitInit(cmd, abs, gitInit)
	if gerr != nil {
		return gerr
	}
	return printWorkspaceNextSteps(cmd.OutOrStdout(), dir, abs, gitNote)
}

// ensureGitignore appends to path the lines it lacks, creating the file when
// absent and leaving every line already there alone.
func ensureGitignore(path string, lines []string) error {
	data, err := os.ReadFile(path) //nolint:gosec // G304: the workspace's own .gitignore.
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("reading %s: %w", path, err)
	}
	have := map[string]bool{}
	for _, l := range strings.Split(string(data), "\n") {
		have[strings.TrimSpace(l)] = true
	}
	var add []string
	for _, l := range lines {
		if !have[l] {
			add = append(add, l)
		}
	}
	if len(add) == 0 {
		return nil
	}
	content := string(data)
	if content != "" && !strings.HasSuffix(content, "\n") {
		content += "\n"
	}
	content += "# Compiled artifacts and Python caches, regenerated by dexaflow.\n" + strings.Join(add, "\n") + "\n"
	if werr := os.WriteFile(path, []byte(content), 0o644); werr != nil { //nolint:gosec // G306: a committed, non-secret file.
		return fmt.Errorf("writing %s: %w", path, werr)
	}
	return nil
}

// maybeGitInit runs `git init` in dir when asked and dir is not in a work
// tree yet, and returns a line for the summary.
func maybeGitInit(cmd *cobra.Command, dir string, want bool) (string, error) {
	if !want {
		return "", nil
	}
	if root := gitRootOf(cmdContext(cmd), dir); root != "" {
		return "already in the git repository at " + root, nil
	}
	c := exec.CommandContext(cmdContext(cmd), "git", "init", "-q", dir) //nolint:gosec // G204: fixed git binary; dir is the operator's own folder.
	c.Env = gitEnv(os.Environ())
	if out, err := c.CombinedOutput(); err != nil {
		return "", fmt.Errorf("git init %s: %w: %s", dir, err, strings.TrimSpace(string(out)))
	}
	return "initialized a git repository", nil
}

func printWorkspaceNextSteps(out io.Writer, dir, abs, gitNote string) error {
	var b strings.Builder
	fmt.Fprintf(&b, "Initialized Dexaflow workspace in %s\n", abs)
	fmt.Fprintf(&b, "  %-26s targets and shared defaults (commit it; it holds no credentials)\n", workspaceFileName)
	fmt.Fprintf(&b, "  %-26s one folder per DAG\n", "dags/")
	if gitNote != "" {
		fmt.Fprintf(&b, "  git: %s\n", gitNote)
	}
	b.WriteString("\nNext steps:\n")
	if filepath.Clean(dir) != "." {
		fmt.Fprintf(&b, "  cd %s\n", dir)
	}
	b.WriteString("  dexaflow target add dev https://<control-plane> --registry <registry-prefix>\n")
	b.WriteString("  dexaflow new my_dag\n")
	b.WriteString("  dexaflow lite                # run every DAG of the workspace locally\n")
	_, err := io.WriteString(out, b.String())
	return err
}

// dagIDPattern is the dag_id grammar of the project schema.
var dagIDPattern = regexp.MustCompile(`^[a-zA-Z0-9_][a-zA-Z0-9_-]{0,199}$`)

// newNewCommand builds `dexaflow new <name>`: a DAG project under the
// workspace's dags/ folder, written only where nothing would be overwritten.
func newNewCommand() *cobra.Command {
	var force bool
	cmd := &cobra.Command{
		Use:   "new <dag_id>",
		Short: "Scaffold a new DAG under the workspace's dags/ folder.",
		Long: "Writes dags/<dag_id>/dexaflow.yaml, dag.py and .gitignore in the workspace found\n" +
			"from the current directory. Existing files are never overwritten without --force.\n" +
			"Outside a workspace, use `dexaflow workspace init` first, or `dexaflow init <path>`\n" +
			"for a single project.",
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return runNew(cmd, args[0], force)
		},
	}
	cmd.Flags().BoolVar(&force, "force", false, "overwrite the scaffold files when they already exist")
	return cmd
}

func runNew(cmd *cobra.Command, dagID string, force bool) error {
	if !dagIDPattern.MatchString(dagID) {
		return fmt.Errorf("invalid DAG id %q: use letters, digits, '_' and '-' (it names the folder and the DAG)", dagID)
	}
	ws, err := findWorkspaceFromCwd()
	if err != nil {
		return err
	}
	if ws == nil {
		return fmt.Errorf("no %s found here or in any parent folder.\n"+
			"  - create a workspace:       dexaflow workspace init\n"+
			"  - or a single project:      dexaflow init %s", workspaceFileName, dagID)
	}
	dir := filepath.Join(ws.Root, "dags", dagID)
	if derr := checkDagIDFree(ws.Root, dir, dagID); derr != nil {
		return derr
	}
	if werr := writeScaffold(dir, dagID, force); werr != nil {
		return werr
	}
	return printNewNextSteps(cmd, dir, dagID)
}

// checkDagIDFree refuses a dag_id another project of the workspace already
// uses: the second one would fail discovery for the whole workspace.
func checkDagIDFree(root, dir, dagID string) error {
	projects, err := DiscoverProjects(root)
	if err != nil {
		// Discovery reports its own problems (a duplicate already there) on
		// the next command; the scaffold does not depend on it.
		return nil //nolint:nilerr // see above.
	}
	for _, p := range projects {
		if p.DagID == dagID && filepath.Clean(p.Path) != filepath.Clean(dir) {
			return fmt.Errorf("DAG id %q is already used by the project in %s", dagID, p.Path)
		}
	}
	return nil
}

// writeScaffold writes the starter files into dir. Without force it refuses,
// before writing anything, when any of them already exists.
func writeScaffold(dir, dagID string, force bool) error {
	files := map[string]string{
		projectConfigFile: fmt.Sprintf(leoflowTemplate, dagID),
		"dag.py":          fmt.Sprintf(dagTemplate, dagID, dagID),
		".gitignore":      gitignoreTemplate,
	}
	if !force {
		var existing []string
		for _, name := range []string{projectConfigFile, legacyProjectConfigFile, "dag.py", ".gitignore"} {
			if fileExists(filepath.Join(dir, name)) {
				existing = append(existing, name)
			}
		}
		if len(existing) > 0 {
			return fmt.Errorf("%s already has %s; nothing was written. Pass --force to overwrite", dir, strings.Join(existing, ", "))
		}
	}
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return fmt.Errorf("creating %s: %w", dir, err)
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil { //nolint:gosec // G306: scaffold files are non-sensitive source.
			return fmt.Errorf("writing %s: %w", name, err)
		}
	}
	return nil
}

// printNewNextSteps names the workspace's active target, so the deploy step
// says where it goes, or how to add one.
func printNewNextSteps(cmd *cobra.Command, dir, dagID string) error {
	shown := dir
	if wd, err := os.Getwd(); err == nil {
		if rel, rerr := filepath.Rel(wd, dir); rerr == nil {
			shown = rel
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "Created DAG %q in %s\n\nNext steps:\n", dagID, shown)
	fmt.Fprintf(&b, "  dexaflow validate %s\n", shown)
	b.WriteString("  dexaflow lite                     # run every DAG of the workspace locally\n")
	var active *activeTarget
	if tc, err := loadTargetContext(cmd); err == nil {
		active, _ = tc.selectTarget(cmd) //nolint:errcheck // a bad selection only drops the hint; the deploy reports it.
	}
	if active != nil {
		fmt.Fprintf(&b, "  dexaflow deploy %s   # to target %s (%s)\n", dagID, active.Name, active.Server)
	} else {
		b.WriteString("  dexaflow target add dev https://<control-plane>   # where deploys go\n")
		fmt.Fprintf(&b, "  dexaflow deploy %s\n", dagID)
	}
	_, err := io.WriteString(cmd.OutOrStdout(), b.String())
	return err
}
